"""Synthetic :class:`~unimri.data.MRIData` for every sampling pattern.

``synthetic_dataset(pattern)`` returns a *valid* dataset plus the exact
ground-truth image it was simulated from. k-space is generated by the reference
:mod:`unimri.testing.ndft`, so these fixtures also serve to validate fast
operators against a known answer.

Kept small (default 24-32 px, 1-4 coils) so the brute-force transform is fast
enough for unit tests and CI.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from unimri.data import (
    AcquisitionInfo,
    CoilInfo,
    EncodingSpace,
    FieldOfView,
    MRIData,
    SamplingPattern,
    Trajectory,
    TrajectoryUnits,
)
from unimri.testing import phantoms, trajectories
from unimri.testing.ndft import ndft_forward


@dataclass
class SyntheticDataset:
    """A synthetic dataset and everything needed to score a reconstruction of it."""

    data: MRIData
    ground_truth: np.ndarray  # exact image, shape (ny, nx) or (nz, ny, nx)
    coil_maps: np.ndarray | None  # (n_coils, *image_shape) or None for single-coil


def _birdcage_maps(n_coils: int, shape: tuple[int, ...]) -> np.ndarray:
    """Cheap smooth complex sensitivity maps (a ring of coils around the FOV)."""
    if n_coils == 1:
        return np.ones((1, *shape), dtype=np.complex128)
    grids = np.meshgrid(*[np.linspace(-1, 1, n) for n in shape], indexing="ij")
    maps = np.empty((n_coils, *shape), dtype=np.complex128)
    for c in range(n_coils):
        ang = 2 * np.pi * c / n_coils
        cx, cy = 1.5 * np.cos(ang), 1.5 * np.sin(ang)
        d2 = (grids[-1] - cx) ** 2 + (grids[-2] - cy) ** 2
        maps[c] = np.exp(-d2) * np.exp(1j * ang)
    maps /= np.sqrt((np.abs(maps) ** 2).sum(0, keepdims=True) + 1e-9)
    return maps


def synthetic_dataset(
    pattern: SamplingPattern | str = SamplingPattern.RADIAL,
    *,
    matrix: int = 28,
    n_coils: int = 1,
    noise_std: float = 0.0,
    seed: int = 0,
) -> SyntheticDataset:
    """Build one valid :class:`MRIData` for ``pattern`` with known ground truth."""
    pattern = SamplingPattern(pattern)
    rng = np.random.default_rng(seed)

    # -- ground-truth image + coil maps -------------------------------------
    if pattern in {SamplingPattern.STACK_OF_STARS}:
        nz = max(4, matrix // 4)
        gt = phantoms.ellipsoid_phantom((nz, matrix, matrix))
        img_shape: tuple[int, ...] = (nz, matrix, matrix)
        recon_matrix = (matrix, matrix, nz)
        n_dims = 3
    else:
        gt = phantoms.shepp_logan((matrix, matrix))
        img_shape = (matrix, matrix)
        recon_matrix = (matrix, matrix, 1)
        n_dims = 2
    maps = _birdcage_maps(n_coils, img_shape)

    # -- trajectory --------------------------------------------------------
    dcf: np.ndarray | None = None
    if pattern is SamplingPattern.CARTESIAN:
        trajectory = None
        coords = trajectories.cartesian(matrix, n_dims=2)  # only used to simulate k-space
        kspace_axes = ("coil", "ky", "kx")
    elif pattern is SamplingPattern.RADIAL:
        coords, dcf = trajectories.radial_2d(matrix, n_spokes=max(16, 3 * matrix))
        trajectory = Trajectory(coords, TrajectoryUnits.NORMALIZED, density_compensation=dcf)
        kspace_axes = ("coil", "shot", "readout")
    elif pattern is SamplingPattern.STACK_OF_STARS:
        coords, dcf = trajectories.stack_of_stars(
            matrix, n_spokes=max(12, 2 * matrix), n_partitions=img_shape[0]
        )
        trajectory = Trajectory(coords, TrajectoryUnits.NORMALIZED, density_compensation=dcf)
        kspace_axes = ("coil", "shot", "readout")
    else:
        raise NotImplementedError(f"synthetic_dataset does not cover {pattern.value} yet")

    # -- simulate k-space via the reference transform --------------------
    per_coil = []
    for c in range(n_coils):
        coil_img = maps[c] * gt
        samples = ndft_forward(coil_img.astype(np.complex128), coords)
        per_coil.append(samples)
    kspace = np.stack(per_coil, axis=0)

    if pattern is SamplingPattern.CARTESIAN:
        kspace = kspace.reshape(n_coils, matrix, matrix)
    else:
        kspace = kspace.reshape(n_coils, *coords.shape[1:])

    if noise_std > 0:
        kspace = kspace + noise_std * (
            rng.standard_normal(kspace.shape) + 1j * rng.standard_normal(kspace.shape)
        )
    kspace = kspace.astype(np.complex64)

    data = MRIData(
        kspace=kspace,
        kspace_axes=kspace_axes,
        encoding=EncodingSpace(
            recon_matrix=recon_matrix,
            encoded_matrix=recon_matrix,
            fov=FieldOfView(200.0, 200.0, 200.0 if n_dims == 3 else 5.0),
            sampling=pattern,
            n_dims=n_dims,
        ),
        acquisition=AcquisitionInfo(nucleus="1H", field_strength_t=3.0, sequence_name="synthetic"),
        coils=CoilInfo(n_channels=n_coils),
        trajectory=trajectory,
    )
    data.provenance.record("synthetic_dataset", params={"pattern": pattern.value, "matrix": matrix})
    data.validate()
    return SyntheticDataset(data=data, ground_truth=gt, coil_maps=maps if n_coils > 1 else None)


AVAILABLE_PATTERNS: tuple[SamplingPattern, ...] = (
    SamplingPattern.CARTESIAN,
    SamplingPattern.RADIAL,
    SamplingPattern.STACK_OF_STARS,
)
